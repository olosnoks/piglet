// ----------------------------------------------------------------
//  Pig behaviour, 20 fps. Modes follow the node state:
//    searching  -> sniff, look both ways, "?"
//    linked     -> trot while the world scrolls; stop to sniff, dig
//                  truffles, turn round now and then, hop on each new network
//    idle       -> linked but nothing new for PIG_SLEEP_MS: sleep, "zZ"
// ----------------------------------------------------------------
static const uint32_t PIG_SLEEP_MS = 60000;
static uint32_t lastNewMs = 0;   // last time a never-seen BSSID turned up
static uint32_t lastWakeMs = 0;  // last time something else (a party) woke the pig

// ----------------------------------------------------------------
//  Friends — other Piglet C3 nodes. Each node tags its heartbeat
//  text field (len stays 0, so the Core still sees an empty heartbeat):
//    [0..3] "PIG1"   [4..7] unique networks found   [8..9] party
//    countdown in 100 ms steps (0 = none)   [10] party id
//  Nearby friends join our pig on screen as a flock (up to 6 pigs).
// ----------------------------------------------------------------
static const uint32_t FRIEND_NEAR_MS = 45000;   // nearby if heard within this long
static const int      MAX_FRIENDS    = 6;
static const int      MAX_FLOCK      = 5;       // friends on screen, so 6 pigs with ours

struct Friend {
  bool     used, hopPending;
  uint8_t  mac[6];
  uint32_t firstMs, lastMs, nets;
  uint16_t hellos;
  int8_t   rssi;
};
static Friend  friends[MAX_FRIENDS];
static uint8_t myMac[6];

// Filled in by the ESP-Now callback, consumed by friendsTick() in the main loop
struct FriendMsg { uint8_t mac[6]; int8_t rssi; uint32_t nets; uint16_t partyCd; uint8_t partyId; };
static volatile bool friendPending = false;
static FriendMsg     friendMsg;

// Shared party: the node with the lowest MAC leads and announces a countdown
static uint32_t partyAtMs   = 0;    // when the next party starts (0 = none)
static bool     hostingParty = false;
static uint8_t  partyId     = 0;
static uint32_t nextPartyMs = 0;    // leader: when to announce the next one

static void friendName(const uint8_t* mac, char* out) { snprintf(out, 5, "%02X%02X", mac[4], mac[5]); }
static bool friendNear(const Friend& f) { return f.used && millis() - f.lastMs < FRIEND_NEAR_MS; }

// Leader = lowest MAC among us and the friends we can hear
static bool isLowest(const uint8_t* mac) {
  if (memcmp(mac, myMac, 6) > 0) return false;
  for (const Friend& f : friends)
    if (friendNear(f) && memcmp(f.mac, mac, 6) < 0) return false;
  return true;
}

static void friendsTick() {
  if (!friendPending) return;
  FriendMsg m;
  memcpy(&m, (const void*)&friendMsg, sizeof(m));
  friendPending = false;

  uint32_t now = millis();
  int slot = -1;
  for (int i = 0; i < MAX_FRIENDS; i++)
    if (friends[i].used && memcmp(friends[i].mac, m.mac, 6) == 0) { slot = i; break; }
  if (slot < 0) {                                 // new friend: free slot, else the stalest
    slot = 0;
    for (int i = 0; i < MAX_FRIENDS; i++) {
      if (!friends[i].used) { slot = i; break; }
      if (friends[i].lastMs < friends[slot].lastMs) slot = i;
    }
    friends[slot] = {};
    friends[slot].used = true;
    friends[slot].firstMs = now;
    memcpy(friends[slot].mac, m.mac, 6);
  }
  Friend& f = friends[slot];
  bool wasNear = f.hellos > 0 && now - f.lastMs < FRIEND_NEAR_MS;
  if (wasNear && m.nets > f.nets) f.hopPending = true;   // its node found a network: its pig hops
  f.nets   = m.nets;
  f.lastMs = now;
  f.rssi   = m.rssi;
  f.hellos++;
  if (!wasNear) {
    char name[5];
    friendName(f.mac, name);
    Serial.printf("[FRIEND] %s nearby (rssi %d)\n", name, m.rssi);
  }
  // Join the leader's party countdown
  if (m.partyCd && m.partyId != partyId && isLowest(m.mac)) {
    partyId      = m.partyId;
    partyAtMs    = now + m.partyCd * 100u;
    hostingParty = false;
  }
}

