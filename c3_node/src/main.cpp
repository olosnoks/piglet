static const FlockSize& flockSize(int n) { return n <= 2 ? SIZE_L : n <= 4 ? SIZE_M : SIZE_S; }

// edge = true draws a 1 px black border (not below the hooves) so overlapping pigs stay separate
static void drawPig(const PigSet& s, uint8_t f, int x, int y, bool flip, bool edge, uint8_t look) {
  if (edge) blit(s.edges + f * s.h, s.w + 2, s.h, x - 1, y, flip, 0);
  else      blit(s.masks + f * s.h, s.w, s.h, x, y, flip, 0);
  blit(s.frames + (look * PF_COUNT + f) * s.h, s.w, s.h, x, y, flip, 1);
}

// Each pig's look (spot pattern) comes from a hash of its node's address. If two pigs in the
// flock land on the same look, the one with the higher address takes the next free look.
// Every node sorts the same addresses the same way, so a pig looks the same on every screen.
static uint8_t lookHash(const uint8_t* mac) {
  uint32_t h = 2166136261u;
  for (int i = 0; i < 6; i++) h = (h ^ mac[i]) * 16777619u;
  return h % PIG_LOOKS;
}
static void assignLooks(const uint8_t* const* macs, uint8_t* looks, int n) {
  int order[6];
  for (int i = 0; i < n; i++) order[i] = i;
  for (int i = 1; i < n; i++)                          // insertion sort by address
    for (int j = i; j > 0 && memcmp(macs[order[j]], macs[order[j - 1]], 6) < 0; j--) {
      int tmp = order[j]; order[j] = order[j - 1]; order[j - 1] = tmp;
    }
  bool taken[PIG_LOOKS] = {false};
  for (int k = 0; k < n; k++) {
    uint8_t v = lookHash(macs[order[k]]);
    while (taken[v]) v = (v + 1) % PIG_LOOKS;
    taken[v] = true;
    looks[order[k]] = v;
  }
}

// Crouch, jump, land — used for our pig and for friends when their node finds a network
static bool hopAt(int k, int jump, uint8_t& f, int& dy) {
  dy = 0;
  if (k < 2)  { f = PF_CROUCH; return true; }
  if (k < 14) { int i = k - 2; f = PF_JUMP; dy = (int)lroundf(i * (11 - i) / 30.25f * jump); return true; }
  if (k < 16) { f = PF_LAND; return true; }
  return false;
}

// Party: everyone jumps together. 2 pigs: one jump + hearts. 3-4: two jumps + confetti.
// 5-6: three jumps + confetti + fireworks.
static int partyJumps(int n) { return n <= 2 ? 1 : n <= 4 ? 2 : 3; }
static bool partyAt(int k, int n, int jump, uint8_t& f, int& dy, bool& peak, bool& hearts) {
  int J = partyJumps(n);
  peak = hearts = false; dy = 0;
  if (k < J * 20) {
    int j = k % 20;
    if (!hopAt(j, jump, f, dy)) f = PF_HAPPY;
    peak = (j == 7);
    return true;
  }
  if (k < J * 20 + 18) { f = PF_HAPPY; hearts = (k == J * 20); return true; }
  if (k < J * 20 + 24) { f = PF_STAND; return true; }
  return false;
}

