// ================================================================
//  Effective 2.4 GHz scan range
//  Clamp the Core's assignment to 2.4 GHz. If the assignment is
//  entirely 5 GHz, fall back to all of 2.4 GHz so the node stays useful.
// ================================================================
static bool effRange(uint8_t& s, uint8_t& e) {
  s = startIdx;
  e = (endIdx > LAST_24G_IDX) ? LAST_24G_IDX : endIdx;
  if (s > LAST_24G_IDX || e < s) {
    s = 0;
    e = LAST_24G_IDX;
    return true;  // fallback in use
  }
  return false;
}

// ================================================================
//  Unique BSSID tracking (FNV-1a hash set, open addressing)
//  Returns true the first time a BSSID is seen. Stops adding once
//  SEEN_MAX is reached, so very long sessions just stop hopping.
// ================================================================
static const uint16_t SEEN_CAP = 1024;           // power of two
static const uint16_t SEEN_MAX = SEEN_CAP * 7 / 8;
static uint32_t seenHash[SEEN_CAP] = {0};
static uint16_t seenCount = 0;

static bool markSeen(const uint8_t* bssid) {
  uint32_t h = 2166136261u;
  for (int i = 0; i < 6; i++) h = (h ^ bssid[i]) * 16777619u;
  if (h == 0) h = 1;  // 0 marks an empty slot
  uint16_t i = h & (SEEN_CAP - 1);
  while (seenHash[i]) {
    if (seenHash[i] == h) return false;
    i = (i + 1) & (SEEN_CAP - 1);
  }
  if (seenCount >= SEEN_MAX) return false;
  seenHash[i] = h;
  seenCount++;
  return true;
}

// ================================================================
//  BLE — JCMK-style: a short active scan in the ch-6 admin window after
//  each Wi-Fi cycle. Each new address goes to the Core once, as
//    MAC,NAME,[BLE],0,RSSI,B
//  (JCMK node format; Piglet Core needs the ble-core patch to log it as
//  a WiGLE "BLE" row). Phones rotate random addresses, so the BLE seen-set
//  is cleared when full rather than frozen like the Wi-Fi one.
// ================================================================
static const uint32_t BLE_SCAN_MS   = 500;
static const uint16_t BLE_SEEN_CAP  = 2048;              // power of two
static const uint16_t BLE_SEEN_MAX  = BLE_SEEN_CAP * 7 / 8;
static uint32_t bleSeenHash[BLE_SEEN_CAP] = {0};
static uint16_t bleSeenCount = 0;

static bool bleMarkSeen(const uint8_t* addr) {
  uint32_t h = 2166136261u;
  for (int i = 0; i < 6; i++) h = (h ^ addr[i]) * 16777619u;
  if (h == 0) h = 1;
  uint16_t i = h & (BLE_SEEN_CAP - 1);
  while (bleSeenHash[i]) {
    if (bleSeenHash[i] == h) return false;
    i = (i + 1) & (BLE_SEEN_CAP - 1);
  }
  if (bleSeenCount >= BLE_SEEN_MAX) {                    // full: start over
    memset(bleSeenHash, 0, sizeof(bleSeenHash));
    bleSeenCount = 0;
    i = h & (BLE_SEEN_CAP - 1);
  }
  bleSeenHash[i] = h;
  bleSeenCount++;
  return true;
}

// Results arrive in the NimBLE host task; queue them for the main loop,
// which dedupes and sends on ch 6. Single producer, single consumer.
struct BleHit { uint8_t addr[6]; int8_t rssi; char mac[18]; char name[33]; };
static const uint8_t BLE_Q = 32;
static BleHit           bleQ[BLE_Q];
static volatile uint8_t bleQHead = 0, bleQTail = 0;
static NimBLEScan*      bleScan  = nullptr;

class BleScanCb : public NimBLEScanCallbacks {
  void onResult(const NimBLEAdvertisedDevice* d) override {
    bleSeenTotal++;
    uint8_t next = (bleQTail + 1) % BLE_Q;
    if (next == bleQHead) return;                       // queue full: drop
    BleHit& e = bleQ[bleQTail];
    const NimBLEAddress& a = d->getAddress();
    memcpy(e.addr, a.getVal(), 6);
    e.rssi = (int8_t)d->getRSSI();
    snprintf(e.mac, sizeof(e.mac), "%s", a.toString().c_str());
    for (char* p = e.mac; *p; p++) *p = toupper(*p);    // match WiFi.BSSIDstr()
    // Name goes in the SSID field: strip commas/control chars so the CSV parsers don't split it
    std::string nm = d->haveName() ? d->getName() : std::string();
    size_t k = 0;
    for (char c : nm) {
      if (k >= sizeof(e.name) - 1) break;
      e.name[k++] = (c == ',' || (uint8_t)c < 0x20 || c == 0x7f) ? ' ' : c;
    }
    e.name[k] = '\0';
    bleQTail = next;
  }
};
static BleScanCb bleCb;

static void bleInit() {
  NimBLEDevice::init("");
  bleScan = NimBLEDevice::getScan();
  bleScan->setScanCallbacks(&bleCb, false);   // report each address once per scan
  bleScan->setActiveScan(true);               // ask for scan responses, which carry most names
  bleScan->setInterval(100);
  bleScan->setWindow(99);
  bleScan->setMaxResults(0);                  // don't keep results; we queue them ourselves
}

static bool bleBusy() { return bleScan && bleScan->isScanning(); }

