// sp = spacing between pigs, lead = gap ahead of the leader, back = rise of the back row
struct FlockSize { const PigSet* own; const PigSet* fr; uint8_t sp, lead; int8_t back; uint8_t jump; };
static const FlockSize SIZE_L = {&SET_L, &SET_FL, 22, 12, -3, 13};
